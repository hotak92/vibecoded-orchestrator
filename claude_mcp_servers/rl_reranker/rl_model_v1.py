    # ------------------------------------------------------------------
    # Private: input preparation
    # ------------------------------------------------------------------

    def _build_inputs(
        self,
        q_raw: "np.ndarray",
        n_raw: "np.ndarray",
        linked_raws: "list[np.ndarray]",
        n_type_idx: int,
        linked_type_idxs: "list[int] | None" = None,
    ) -> "tuple[torch.Tensor, torch.Tensor, torch.Tensor]":
        """Build (entities, type_idxs, slot_scalars) tensors for the neural net.

        Per-slot cosine features are computed from the raw embeddings:
          Query slot:       cos_to_query=1.0, cos_to_target=1.0  (identity anchor)
          Target node slot: cos_to_query=cos(query, node), cos_to_target=1.0
          Linked slots:     cos_to_query=cos(query, slot), cos_to_target=cos(node, slot)
          NULL padding:     cos_to_query=0.0, cos_to_target=0.0

        linked_type_idxs: per-slot type index for each element of linked_raws.
            When None, all linked slots use UNKNOWN_TYPE_IDX.
            Padding slots (beyond len(linked_raws)) always use NULL_TYPE_IDX.
        """
        # Compute cos(query, node) once -- shared by query and node slots
        cos_qn = _cosine_np(q_raw, n_raw)

        # Co-shuffle embeddings and type indices together.
        l_types = list(linked_type_idxs) if linked_type_idxs else [UNKNOWN_TYPE_IDX] * len(linked_raws)
        pairs = list(zip(linked_raws, l_types))
        random.shuffle(pairs)
        shuffled_embs = [p[0] for p in pairs]
        shuffled_types = [p[1] for p in pairs]

        entity_list: list["np.ndarray"] = [q_raw, n_raw]
        type_idx_list: list[int] = [QUERY_TYPE_IDX, n_type_idx]
        # Per-slot cosine features: (cos_to_query, cos_to_target)
        slot_cos_list: list[tuple[float, float]] = [
            (1.0, 1.0),         # query slot: identity anchor (both cos = 1.0)
            (cos_qn, 1.0),      # target node slot: cos_to_query=cos_qn, cos_to_target=1.0
        ]

        zeros = np.zeros(self._emb_dim, dtype=np.float32)
        for i in range(MAX_LINKED):
            if i < len(shuffled_embs):
                slot_emb = shuffled_embs[i].astype(np.float32)
                entity_list.append(slot_emb)
                type_idx_list.append(shuffled_types[i])
                cos_to_query = _cosine_np(q_raw, slot_emb)
                cos_to_target = _cosine_np(n_raw, slot_emb)
                slot_cos_list.append((cos_to_query, cos_to_target))
            else:
                entity_list.append(zeros)
                type_idx_list.append(NULL_TYPE_IDX)
                slot_cos_list.append((0.0, 0.0))  # padding

        entities_np = np.stack(entity_list, axis=0).astype(np.float32)  # (7, emb_dim)
        entities_t = torch.from_numpy(entities_np).unsqueeze(0)          # (1, 7, emb_dim)
        type_idxs_t = torch.tensor([type_idx_list], dtype=torch.long)    # (1, 7)
        slot_scalars_t = torch.tensor(
            [slot_cos_list], dtype=torch.float32                          # (1, 7, 2)
        )
        return entities_t, type_idxs_t, slot_scalars_t

    # ------------------------------------------------------------------
    # Private: type registry
    # ------------------------------------------------------------------

    def _register_new_type(self, node_type: str) -> int:
        if self._next_type_slot >= _MAX_TYPES:
            logger.warning(
                "RLModel: type slot limit (%d) reached; mapping '%s' to UNKNOWN_TYPE_IDX",
                _MAX_TYPES, node_type,
            )
            return UNKNOWN_TYPE_IDX
        new_idx = self._next_type_slot
        self._next_type_slot += 1
        # Mean of builtin type embeddings as initialization
        with torch.no_grad():
            builtin_mean = self._net.type_embs.weight[:len(NODE_TYPES)].mean(0)
            self._net.type_embs.weight[new_idx] = builtin_mean
        self._type_registry[node_type] = new_idx
        msg = (
            f"[RLModel] New node type auto-registered: '{node_type}' -> index {new_idx}. "
            f"Embedding initialized from mean of {len(NODE_TYPES)} builtin types. "
            f"Add '{node_type}' to NODE_TYPES in rl_model.py to make it permanent."
        )
        self._new_type_messages.append(msg)
        logger.info("RLModel: auto-registered type '%s' at slot %d", node_type, new_idx)
        return new_idx

    # ------------------------------------------------------------------
    # Private: weight initialisation
    # ------------------------------------------------------------------

    def _init_weights(self) -> None:
        """He-init for encoder/MLP linear layers; small uniform for type embeddings."""
        for m in self._net.modules():
            if isinstance(m, nn.Linear):
                nn.init.kaiming_normal_(m.weight, nonlinearity="relu")
                if m.bias is not None:
                    nn.init.zeros_(m.bias)
        nn.init.normal_(self._net.type_embs.weight, 0.0, 0.1)
        n_params = sum(p.numel() for p in self._net.parameters())
        logger.debug(
            "RLModel: fresh weights (emb_dim=%d input_dim=%d params=%dk)",
            self._emb_dim, INPUT_DIM, n_params // 1000,
        )

    # ------------------------------------------------------------------
    # Private: persistence
    # ------------------------------------------------------------------

    def _try_load(self) -> bool:
        """Try .pt checkpoint first; fall back to .npz migration."""
        if self._pt_path.exists():
            return self._load_pt(self._pt_path)
        # Migration: look for old .npz file at the originally configured path
        npz_path = self._state_path if str(self._state_path).endswith(".npz") else \
            self._state_path.with_suffix(".npz")
        if npz_path.exists():
            return self._migrate_from_npz(npz_path)
        return False

    def _sanitize_registry(self) -> None:
        """
        Remap dynamic type entries whose index conflicts with a sentinel slot.

        When N_ENTITY_TYPES increased from 8 -> 9 (adding UNKNOWN_TYPE_IDX), old
        dynamic types that were allocated at slot 8 (the first dynamic slot in the
        old system) now shadow UNKNOWN_TYPE_IDX.  This method detects such conflicts
        and relocates them to fresh dynamic slots >= N_ENTITY_TYPES.

        Builtin type names (in NODE_TYPES) are intentionally skipped: get_type_idx()
        resolves them via the NODE_TYPES list before consulting the registry, so
        their stored indices (0-5) are never used as dynamic type lookups.
        """
        _builtin_names = set(NODE_TYPES)
        for name in list(self._type_registry):
            if name in _builtin_names:
                continue  # builtins resolved via NODE_TYPES -- registry entry harmless
            idx = self._type_registry[name]
            if idx < N_ENTITY_TYPES:
                new_idx = self._next_type_slot
                self._next_type_slot += 1
                self._type_registry[name] = new_idx
                logger.info(
                    "RLModel: registry conflict -- remapped '%s' from slot %d -> %d",
                    name, idx, new_idx,
                )

    def _load_pt(self, path: Path) -> bool:
        try:
            ckpt = torch.load(str(path), map_location="cpu", weights_only=True)
            if ckpt.get("emb_dim") != self._emb_dim:
                logger.warning(
                    "RLModel: emb_dim mismatch (%s vs %d), reinitialising",
                    ckpt.get("emb_dim"), self._emb_dim,
                )
                return False

            sd = ckpt["state_dict"]
            old_mlp0 = sd.get("mlp.0.weight")
            is_pre_cross = (
                old_mlp0 is not None and old_mlp0.shape == (384, _OLD_INPUT_DIM)
            )

            if is_pre_cross:
                # --- Migrate pre-cross-path checkpoint ---
                # Load all layers that haven't changed (enc, enc2, ref, ref2,
                # type_embs, mlp[3:]) then reconstruct mlp.0 from old link columns.
                self._init_weights()  # He-init everything (sets cross1/cross2 too)
                exclude = {"mlp.0.weight", "mlp.0.bias",
                           "cross1.weight", "cross1.bias",
                           "cross2.weight", "cross2.bias"}
                partial_sd = {k: v for k, v in sd.items() if k not in exclude}
                self._net.load_state_dict(partial_sd, strict=False)

                # Migrate mlp.0: old columns 112:392 (link slots) → new 128:408
                with torch.no_grad():
                    new_w = self._net.mlp[0].weight.clone()  # (384, 408)
                    new_w[:, CROSS_DIM:] = old_mlp0[:, REF_DIM * 2:]  # copy link cols
                    # cross cols (0:CROSS_DIM) stay He-initialised
                    self._net.mlp[0].weight.copy_(new_w)
                    # bias unchanged (same size)
                    self._net.mlp[0].bias.copy_(sd["mlp.0.bias"])

                logger.info(
                    "RLModel: migrated pre-cross-path checkpoint from %s "
                    "(mlp.0 %s→%s, cross1/cross2 He-init)",
                    path, list(old_mlp0.shape), list(self._net.mlp[0].weight.shape),
                )
            else:
                self._net.load_state_dict(sd)
                try:
                    self._opt.load_state_dict(ckpt["opt_state"])
                except Exception:
                    pass  # optimizer state mismatch -- fresh optimizer is fine

            self._type_registry = dict(ckpt.get("type_registry", {}))
            if not self._type_registry:
                self._type_registry = {t: i for i, t in enumerate(NODE_TYPES)}
            # max(..., N_ENTITY_TYPES) ensures old checkpoints (saved when
            # N_ENTITY_TYPES was 8) don't clobber the new UNKNOWN slot at 8.
            self._next_type_slot = max(
                ckpt.get("next_type_slot", N_ENTITY_TYPES), N_ENTITY_TYPES
            )
            self._sanitize_registry()
            logger.debug("RLModel: loaded checkpoint from %s", path)
            return True
        except Exception as exc:
            logger.warning("RLModel: failed to load .pt checkpoint: %s", exc)
            return False

    def _migrate_from_npz(self, npz_path: Path) -> bool:
        """
        Migrate type embeddings + registry from old .npz to the new PyTorch model.

        Only type_embs[:8] and the type registry are migrated -- these are
        independent of the encoder/MLP chain and remain valid.
        All layers are He-reinitialised; type_embs are then overwritten.
        """
        if not _HAS_NUMPY:
            return False
        try:
            d = np.load(str(npz_path), allow_pickle=False)
        except Exception as exc:
            logger.warning("RLModel: failed to load .npz for migration: %s", exc)
            return False

        # Check if this is definitely a compatible old file
        if "type_embs" not in d:
            logger.info("RLModel: .npz has no type_embs, starting fresh")
            return False

        self._init_weights()  # He-init everything

        with torch.no_grad():
            old_embs = torch.from_numpy(d["type_embs"][:N_ENTITY_TYPES].astype(np.float32))
            self._net.type_embs.weight[:N_ENTITY_TYPES].copy_(old_embs)

            if "type_registry_keys" in d:
                keys = [str(k) for k in d["type_registry_keys"]]
                vals = [int(v) for v in d["type_registry_vals"]]
                self._type_registry = dict(zip(keys, vals))
                self._next_type_slot = max(vals) + 1 if vals else N_ENTITY_TYPES
                self._next_type_slot = max(self._next_type_slot, N_ENTITY_TYPES)
            self._sanitize_registry()

        logger.info(
            "RLModel: migrated type_embs[:%d] + registry from %s; "
            "all MLP/encoder weights reinitialised fresh. "
            "Run offline_trainer on logged data to retrain.",
            N_ENTITY_TYPES, npz_path,
        )
        return True
