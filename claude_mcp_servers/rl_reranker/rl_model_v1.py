class RLModel:
    """
    Tiny shared-encoder MLP trained online for node relevance scoring.

    All entities (query, node, linked nodes) go through the same encoder +
    refinement pipeline.  The query gets QUERY_TYPE_IDX; missing linked-node
    slots get NULL_TYPE_IDX with a zero raw embedding.

    Per-slot cosine features (cos_to_query, cos_to_target) are computed
    internally from the raw embeddings and injected at the refinement layer.

    Args:
        emb_dim:    Input embedding dimension (1024 for KG, 768 for code graph).
        state_path: Where to load/save weights (.pt file; .npz migration supported).
    """

    def __init__(self, emb_dim: int, state_path: Path) -> None:
        if not _HAS_TORCH:
            raise ImportError(
                "PyTorch is required for RLModel. Install with: pip install torch"
            )
        self._emb_dim = emb_dim
        self._state_path = Path(state_path)
        # Always save/load as .pt regardless of configured extension
        self._pt_path = self._state_path.with_suffix(".pt")

        self._type_registry: dict[str, int] = {t: i for i, t in enumerate(NODE_TYPES)}
        self._new_type_messages: list[str] = []
        self._next_type_slot: int = N_ENTITY_TYPES  # first dynamic slot = 8

        self._net = _RLNetV1(emb_dim)
        self._opt = torch.optim.AdamW(
            self._net.parameters(), lr=LR_MODEL, weight_decay=WEIGHT_DECAY
        )

        if not self._try_load():
            self._init_weights()

    # ------------------------------------------------------------------
    # Inference
    # ------------------------------------------------------------------

    def score(
        self,
        q_raw: "np.ndarray",
        n_raw: "np.ndarray",
        linked_raws: "list[np.ndarray]",
        n_type_idx: int,
        linked_type_idxs: "list[int] | None" = None,
    ) -> float:
        """Compute relevance score in [0, 1].  No gradient.

        Per-slot cosine features are computed internally from the raw embeddings.
        """
        entities_t, type_idxs_t, slot_scalars_t = self._build_inputs(
            q_raw, n_raw, linked_raws, n_type_idx,
            linked_type_idxs=linked_type_idxs,
        )
        self._net.eval()
        with torch.no_grad():
            out = self._net(entities_t, type_idxs_t, slot_scalars_t)
        return float(out[0, 0])

    def score_batch(
        self,
        q_raw: "np.ndarray",
        candidates: "list[tuple[np.ndarray, list[np.ndarray], int, list[int] | None]]",
    ) -> "list[float]":
        """Score multiple candidates against the same query.  No gradient.

        Args:
            q_raw:      Query embedding (1D array of emb_dim).
            candidates: List of (n_raw, linked_raws, n_type_idx, linked_type_idxs)
                        tuples -- one per candidate to score.

        Returns:
            List of relevance scores in [0, 1], same order as candidates.

        This is more efficient than calling score() in a loop because it
        batches all candidates into a single forward pass.
        """
        if not candidates:
            return []
        # Build batched tensors
        all_entities = []
        all_type_idxs = []
        all_slot_scalars = []
        for n_raw, linked_raws, n_type_idx, linked_type_idxs in candidates:
            e, t, s = self._build_inputs(
                q_raw, n_raw, linked_raws, n_type_idx,
                linked_type_idxs=linked_type_idxs,
            )
            all_entities.append(e)
            all_type_idxs.append(t)
            all_slot_scalars.append(s)

        entities_batch = torch.cat(all_entities, dim=0)      # (B, 7, emb_dim)
        type_idxs_batch = torch.cat(all_type_idxs, dim=0)    # (B, 7)
        scalars_batch = torch.cat(all_slot_scalars, dim=0)    # (B, 7, 2)

        self._net.eval()
        with torch.no_grad():
            out = self._net(entities_batch, type_idxs_batch, scalars_batch)  # (B, 1)
        return [float(out[i, 0]) for i in range(out.shape[0])]

    def rerank_candidates(
        self,
        q_raw: "np.ndarray",
        candidates: "list[tuple[np.ndarray, list[np.ndarray], int, list[int] | None, dict]]",
        threshold: float = 0.0,
    ) -> "list[tuple[float, dict]]":
        """Generic reranking: score candidates and return sorted (score, metadata) pairs.

        This is the universal entry point for any reranking use case:
        - KG node reranking (query=search query, candidates=KG nodes)
        - Agent routing (query=task description, candidates=agent representations)
        - Method library ranking (query=task, candidates=stored methods)

        Args:
            q_raw:      Query embedding (1D array of emb_dim).
            candidates: List of (n_raw, linked_raws, n_type_idx, linked_type_idxs, metadata)
                        tuples.  ``metadata`` is an opaque dict passed through to output.
            threshold:  Minimum score to include in results (default: 0.0 = include all).

        Returns:
            List of (score, metadata) sorted descending by score,
            filtered to scores >= threshold.
        """
        if not candidates:
            return []
        batch_input = [
            (n_raw, linked_raws, n_type_idx, linked_type_idxs)
            for n_raw, linked_raws, n_type_idx, linked_type_idxs, _ in candidates
        ]
        scores = self.score_batch(q_raw, batch_input)
        scored = [
            (sc, candidates[i][4])
            for i, sc in enumerate(scores)
            if sc >= threshold
        ]
        scored.sort(key=lambda x: x[0], reverse=True)
        return scored

    # ------------------------------------------------------------------
    # Training
    # ------------------------------------------------------------------

    def update(
        self,
        q_raw: "np.ndarray",
        n_raw: "np.ndarray",
        linked_raws: "list[np.ndarray]",
        n_type_idx: int,
        target: float,
        linked_type_idxs: "list[int] | None" = None,
    ) -> float:
        """One online AdamW step.  Returns BCE loss for logging.

        Per-slot cosine features are computed internally from the raw embeddings.
        """
        entities_t, type_idxs_t, slot_scalars_t = self._build_inputs(
            q_raw, n_raw, linked_raws, n_type_idx,
            linked_type_idxs=linked_type_idxs,
        )
        target_t = torch.tensor([[target]], dtype=torch.float32)

        self._net.train()
        self._opt.zero_grad()
        out = self._net(entities_t, type_idxs_t, slot_scalars_t)
        loss = F.binary_cross_entropy(out, target_t)
        loss.backward()
        self._opt.step()
        return float(loss.detach())

    # ------------------------------------------------------------------
    # Public helpers
    # ------------------------------------------------------------------

    def get_type_idx(self, node_type: str) -> int:
        """Return type-embedding index for node_type; auto-register new types.

        Returns UNKNOWN_TYPE_IDX for empty/None node_type (node exists but type
        not known).  NULL_TYPE_IDX is reserved exclusively for padding slots
        (no linked node present at all).
        """
        if not node_type:
            return UNKNOWN_TYPE_IDX
        idx = self._type_registry.get(node_type)
        if idx is None:
            idx = self._register_new_type(node_type)
        return idx

    def pop_new_type_messages(self) -> list[str]:
        """Return and clear pending new-type notification messages."""
        msgs = list(self._new_type_messages)
        self._new_type_messages.clear()
        return msgs

    def save(self) -> None:
        """Atomically save weights + optimizer state to .pt checkpoint."""
        try:
            self._pt_path.parent.mkdir(parents=True, exist_ok=True)
            _atomic_torch_save(
                {
                    "state_dict": self._net.state_dict(),
                    "opt_state": self._opt.state_dict(),
                    "emb_dim": self._emb_dim,
                    "type_registry": dict(self._type_registry),
                    "next_type_slot": self._next_type_slot,
                },
                self._pt_path,
            )
        except Exception as exc:
            logger.warning("RLModel.save failed: %s", exc)

    @classmethod
    def load_or_create(cls, state_path: Path, emb_dim: int = 1024) -> "RLModel":
        """Load existing weights or initialise a fresh model."""
        return cls(emb_dim=emb_dim, state_path=state_path)

