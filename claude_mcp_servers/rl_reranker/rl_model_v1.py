# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

ENC_DIM = 56            # shared encoder (enc + enc2) output dimension
REF_DIM = 56            # refinement layer output dimension (per-slot MLP input)
TYPE_EMB_DIM = 6        # node type embedding dimension
MAX_LINKED = 5          # linked-node input slots (extras filled with null)
N_SCALARS = 0           # per-slot cosines now embedded at refinement layer
_MAX_TYPES = 256        # pre-allocated embedding slots (9 builtin + up to 247 dynamic)

NODE_TYPES: tuple[str, ...] = (
    "concept", "project", "tool", "model", "hardware", "research",
)
NULL_TYPE_IDX: int = len(NODE_TYPES)         # 6 -- padding slot (no linked node)
QUERY_TYPE_IDX: int = NULL_TYPE_IDX + 1     # 7 -- query entity marker
UNKNOWN_TYPE_IDX: int = QUERY_TYPE_IDX + 1  # 8 -- linked node exists but type not available
N_ENTITY_TYPES: int = UNKNOWN_TYPE_IDX + 1  # 9 builtin type slots

# MLP hidden layer sizes
_H1 = 384
_H2 = 192
_H3 = 96
_H4 = 48    # bottleneck
_H5 = 64    # expansion before output

# Cross-path (query × target interaction before link context)
_CROSS_H1 = 192   # intermediate hidden dim
CROSS_DIM = 128   # cross-path output dim fed into MLP

# MLP input: cross_out + MAX_LINKED x link_refined
INPUT_DIM: int = CROSS_DIM + MAX_LINKED * REF_DIM  # = 128 + 280 = 408

# Old INPUT_DIM (pre-cross-path) used for checkpoint migration detection
_OLD_INPUT_DIM: int = REF_DIM * (1 + 1 + MAX_LINKED)  # = 392

LR_MODEL = 1e-3
WEIGHT_DECAY = 1e-4
DROPOUT = 0.2


