class _RLNetV1(_RLNetV1Base):  # type: ignore[misc,valid-type]
    """Inner PyTorch module.  All entities use shared encoder + refinement.

    Refinement layer now takes (ENC_DIM + TYPE_EMB_DIM + 2) input: the 2 extra
    dimensions are per-slot cosine features (cos_to_query, cos_to_target).
    """

    def __init__(self, emb_dim: int) -> None:
        super().__init__()
        self.emb_dim = emb_dim
        self._ref_in = ENC_DIM + TYPE_EMB_DIM + 2  # 64

        self.enc = nn.Linear(emb_dim, ENC_DIM)
        self.enc2 = nn.Linear(ENC_DIM, ENC_DIM)
        self.ref = nn.Linear(self._ref_in, REF_DIM)
        self.ref2 = nn.Linear(REF_DIM, REF_DIM)
        self.type_embs = nn.Embedding(_MAX_TYPES, TYPE_EMB_DIM)
        # Cross-path: query × target interaction (new layers, trained from scratch)
        self.cross1 = nn.Linear(REF_DIM * 2, _CROSS_H1)
        self.cross2 = nn.Linear(_CROSS_H1, CROSS_DIM)
        self.mlp = nn.Sequential(
            nn.Linear(INPUT_DIM, _H1), nn.SiLU(), nn.Dropout(DROPOUT),
            nn.Linear(_H1, _H2),       nn.SiLU(), nn.Dropout(DROPOUT),
            nn.Linear(_H2, _H3),       nn.SiLU(),
            nn.Linear(_H3, _H4),       nn.SiLU(),
            nn.Linear(_H4, _H5),       nn.SiLU(),
            nn.Linear(_H5, 1),         nn.Sigmoid(),
        )

    def _encode_batch(
        self,
        raws: "torch.Tensor",
        tidxs: "torch.Tensor",
        slot_scalars: "torch.Tensor",
    ) -> "torch.Tensor":
        """Encode a batch of entities through shared encoder + refinement.

        Args:
            raws:         (B, N, emb_dim)
            tidxs:        (B, N) int64
            slot_scalars: (B, N, 2) -- per-slot (cos_to_query, cos_to_target)

        Returns: (B, N, REF_DIM)
        """
        B, N, D = raws.shape
        enc = F.silu(self.enc(raws.reshape(B * N, D))).reshape(B, N, ENC_DIM)
        enc = F.silu(self.enc2(enc.reshape(B * N, ENC_DIM))).reshape(B, N, ENC_DIM)
        t = self.type_embs(tidxs)                                # (B, N, TYPE_EMB_DIM)
        ref_in = torch.cat([enc, t, slot_scalars], dim=-1)       # (B, N, _ref_in)
        refined = F.silu(self.ref(ref_in.reshape(B * N, self._ref_in)))
        refined = F.silu(self.ref2(refined))
        return refined.reshape(B, N, REF_DIM)

    def forward(
        self,
        entities: "torch.Tensor",      # (B, 2+MAX_LINKED, emb_dim)
        type_idxs: "torch.Tensor",     # (B, 2+MAX_LINKED) int64
        slot_scalars: "torch.Tensor",   # (B, 2+MAX_LINKED, 2)
    ) -> "torch.Tensor":               # (B, 1)
        B = entities.shape[0]
        refined = self._encode_batch(entities, type_idxs, slot_scalars)  # (B, 2+MAX_LINKED, REF_DIM)

        # Cross path: query × target interaction
        q_ref = refined[:, 0, :]                           # (B, REF_DIM)
        n_ref = refined[:, 1, :]                           # (B, REF_DIM)
        cross = F.silu(self.cross1(torch.cat([q_ref, n_ref], dim=-1)))  # (B, _CROSS_H1)
        cross = F.silu(self.cross2(cross))                               # (B, CROSS_DIM)

        # Link context: all linked-node slots flattened
        link_refs = refined[:, 2:, :].reshape(B, -1)      # (B, MAX_LINKED * REF_DIM)

        # MLP input: [cross_out | link_refs]
        x = torch.cat([cross, link_refs], dim=-1)          # (B, INPUT_DIM)
        return self.mlp(x)


